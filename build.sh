#!/usr/bin/env bash
# Builds build/kitchen-frame.apk without Gradle. Written for Git Bash on Windows (it calls the
# SDK's .exe/.bat tools through cmd); on Linux/macOS drop the .exe/.bat suffixes and cygpath.
#
# Needs: JDK 17 and, under ANDROID_HOME, build-tools 34.0.0 + platforms;android-34.
# Reads the two URLs the app opens from config.properties (copy config.example.properties).
# Install on the frame:  adb install -r build/kitchen-frame.apk
set -euo pipefail
cd "$(dirname "$0")"

[ -f config.properties ] || { echo "config.properties missing - copy config.example.properties"; exit 1; }
prop() { grep -E "^$1=" config.properties | head -1 | cut -d= -f2-; }
CONTROL_URL="$(prop control.url)"
SLIDESHOW_URL="$(prop slideshow.url)"
[ -n "$CONTROL_URL" ] && [ -n "$SLIDESHOW_URL" ] || { echo "control.url and slideshow.url must be set"; exit 1; }

if [ -z "${JAVA_HOME:-}" ]; then
  JAVA_HOME="$(ls -d /c/Program\ Files/Microsoft/jdk-17* 2>/dev/null | head -1 || true)"
fi
[ -n "${JAVA_HOME:-}" ] && export PATH="$JAVA_HOME/bin:$PATH"
ANDROID_HOME="${ANDROID_HOME:-$HOME/android-sdk}"
BT="$ANDROID_HOME/build-tools/34.0.0"
JAR="$ANDROID_HOME/platforms/android-34/android.jar"
# The signing key and its password stay out of the project folder (and out of any repo).
# Updates must be signed with this same key or Android refuses to install them over the old app.
KS="$HOME/.android/kitchen-frame.keystore"
PASS_FILE="$HOME/.android/kitchen-frame.pass"

rm -rf build && mkdir -p build/classes build/gen/kitchenframe assets

# The machine-specific URLs become a generated class, so they never live in the sources.
cat > build/gen/kitchenframe/Config.java <<JAVA
package kitchenframe;

/** Generated by build.sh from config.properties - do not edit. */
final class Config {
  static final String CONTROL_URL = "$CONTROL_URL";
  static final String SLIDESHOW_URL = "$SLIDESHOW_URL";
  private Config() { }
}
JAVA

"$BT/aapt2.exe" link -o build/base.apk -I "$(cygpath -w "$JAR")" --manifest AndroidManifest.xml -A assets \
  --min-sdk-version 23 --target-sdk-version 23 --version-code 1 --version-name 1.0

# -encoding UTF-8: without it javac on Windows reads the sources as cp1252 and "‹" renders as "â€¹".
javac -encoding UTF-8 -nowarn -source 8 -target 8 -classpath "$(cygpath -w "$JAR")" -d build/classes \
  src/kitchenframe/*.java build/gen/kitchenframe/Config.java 2>&1 | grep -v "^warning\|^Note\|bootstrap" || true

# d8 is a .bat; call it through cmd with Windows paths.
CLASSES=$(cd build/classes && find . -name '*.class' | sed 's|^\./|build\\classes\\|; s|/|\\|g' | tr '\n' ' ')
cmd //c "$(cygpath -w "$BT/d8.bat") --min-api 23 --lib $(cygpath -w "$JAR") --output build $CLASSES"

# Git Bash has no zip; the JDK's jar tool adds the dex (-M: no META-INF manifest).
(cd build && jar -uMf base.apk classes.dex)
"$BT/zipalign.exe" -f 4 build/base.apk build/aligned.apk

if [ ! -f "$KS" ]; then
  mkdir -p "$(dirname "$KS")"
  (umask 077; head -c 24 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c 24 > "$PASS_FILE")
  keytool -genkeypair -keystore "$KS" -storepass "$(cat "$PASS_FILE")" -keypass "$(cat "$PASS_FILE")" \
    -alias kitchenframe -keyalg RSA -keysize 2048 -validity 10000 \
    -dname "CN=Kitchen Frame" >/dev/null 2>&1
fi
# apksigner reads the password from the file itself, so it never appears on a command line.
# No --key-pass: given the same file twice, apksigner reads a second line for it. Left out, it
# tries the keystore password, which is the key password too.
cmd //c "$(cygpath -w "$BT/apksigner.bat") sign --ks $(cygpath -w "$KS") --ks-pass file:$(cygpath -w "$PASS_FILE") --out build\\kitchen-frame.apk build\\aligned.apk"
echo "Built build/kitchen-frame.apk"
